using namespace M;
using namespace M::DebugInfo;

namespace LLVM = mlir::LLVM;

namespace {
/// Convert LineTableLocOp into a "nop" equivalent in GCN.
/// LineTableLocOps are generated by inlined calls as a way to register
/// line table locations that don't really correspond to any actual
/// instruction of the program. We lower this op into a nop-equivalent
/// instruction to ensure this line is preserved in the final line table,
/// giving us a way to place breakpoints at these callsites.
struct ConvertLineTableLocOp : public OpRewritePattern<LineTableLocOp> {
  ConvertLineTableLocOp(MLIRContext *ctx, DIAttrTypeReplacer &replacer)
      : OpRewritePattern<LineTableLocOp>(ctx), replacer(replacer) {}

  LogicalResult matchAndRewrite(LineTableLocOp op,
                                PatternRewriter &rewriter) const override {
    LLVM::InlineAsmOp::create(
        rewriter, replacer.replace<LocationAttr>(op.getLoc()), TypeRange{},
        ValueRange{}, "S_NOP 0;", "", /*has_side_effects=*/true,
        /*is_align_stack=*/false, LLVM::TailCallKind::None,
        LLVM::AsmDialectAttr::get(op.getContext(), LLVM::AsmDialect::AD_ATT),
        ArrayAttr());
    rewriter.eraseOp(op);
    return success();
  }

  /// The replacer used to update attributes.
  DIAttrTypeReplacer &replacer;
};
} // namespace

static void populateAMDGPUConversionPatterns(DIAttrTypeReplacer &replacer,
                                             RewritePatternSet &patterns) {
  patterns.add<ConvertLineTableLocOp>(patterns.getContext(), replacer);
}

//===----------------------------------------------------------------------===//
// getAMDGPUAdapter
//===----------------------------------------------------------------------===//

TargetAdapter DebugInfo::getAMDGPUAdapter(bool tradeoffPerfForVariableDI) {
  return TargetAdapter{populateAMDGPUConversionPatterns, [](ModuleOp module) {},
                       [](ModuleOp module) {}};
}
