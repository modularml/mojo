TEST(PrimitiveTypesTest, testBool) {
  // There's no SB API for getting the bit size of a type, but the byte size
  // should be 1.

  StopContext ctx = buildAndLaunch("bool.mojo");
  SBValue trueVar = ctx.frame.FindVariable("true");
  EXPECT_STREQ(trueVar.GetTypeName(), "!kgen.scalar<bool>");
  EXPECT_EQ((int)trueVar.GetByteSize(), 1);
  EXPECT_EQ((int)trueVar.GetChildAtIndex(0).GetValueAsUnsigned(2), 1);
  EXPECT_STREQ(trueVar.GetSummary(), "True");

  SBValue falseVar = ctx.frame.FindVariable("false");
  EXPECT_STREQ(falseVar.GetTypeName(), "!kgen.scalar<bool>");
  EXPECT_EQ((int)falseVar.GetByteSize(), 1);
  EXPECT_EQ((int)falseVar.GetChildAtIndex(0).GetValueAsUnsigned(2), 0);
  EXPECT_STREQ(falseVar.GetSummary(), "False");

  SBValue otherVar = ctx.frame.FindVariable("other");
  EXPECT_STREQ(otherVar.GetTypeName(), "!kgen.scalar<bool>");
  EXPECT_EQ((int)otherVar.GetByteSize(), 1);
  EXPECT_EQ((int)otherVar.GetChildAtIndex(0).GetValueAsUnsigned(2), 1);
  EXPECT_STREQ(otherVar.GetSummary(), "True");
}

TEST(PrimitiveTypesTest, testInvalidScalar) {
  /// Ensures that `scalar<invalid>` is correctly considered as having 0
  /// bytes. It also expects to have an inner data type of `None`.
  /// A very common case where this is found is `Dict`, so we start with a
  /// `Dict` variable and navigate its members until reaching the invalid value.

  StopContext ctx = buildAndLaunch("invalid.mojo");
  SBValue a = ctx.frame.FindVariable("a");
  SBValue x = a.GetChildMemberWithName("x");
  EXPECT_STREQ(x.GetTypeName(), "!kgen.pointer<scalar<invalid>>");
  SBValue invalid = x.GetChildAtIndex(0);
  EXPECT_STREQ(invalid.GetTypeName(), "!kgen.none");
  EXPECT_EQ((int)invalid.GetByteSize(), 0);
}

TEST(PrimitiveTypesTest, testPointerChild) {
  /// Ensures that the child of a pointer type is correctly generated by
  /// the typesystem and has a valid name.
  /// There are two ways to access the pointee type: GetChildAtIndex(0) and
  /// Dereference(). They are equivalent.

  StopContext ctx = buildAndLaunch("pointer.mojo");
  SBValue var = ctx.frame.FindVariable("int_pointer");
  SBValue child = var.GetChildAtIndex(0);
  EXPECT_STREQ(var.Dereference().GetName(), "*int_pointer");
  EXPECT_STREQ(child.GetName(), "[0]"); // TODO: this might be wrong
  EXPECT_STREQ(child.GetValue(), "101");
  EXPECT_STREQ(var.Dereference().GetChildAtIndex(0).GetValue(), "101");
}

