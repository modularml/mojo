static void checkIntPair(SBValue &strct, int fst, int snd) {
  EXPECT_STREQ(strct.GetDisplayTypeName(), "MyPair");
  ASSERT_EQ((int)strct.GetNumChildren(), 2);
  SBValue firstField = strct.GetChildAtIndex(0).GetChildAtIndex(0);
  EXPECT_EQ((int)firstField.GetValueAsSigned(fst - 1), fst);
  SBValue secondField = strct.GetChildAtIndex(1).GetChildAtIndex(0);
  EXPECT_EQ((int)secondField.GetValueAsSigned(snd - 1), snd);
}

TEST(PrimitiveTypesTest, testStructAccess) {
  /// Ensures that the a DType.invalid pointer is correctly parsed.

  StopContext ctx = buildAndLaunch("struct_access.mojo");
  SBValue p = ctx.frame.FindVariable("p");
  checkIntPair(p, 1, 2);

  ctx.resume();
  p = ctx.frame.FindVariable("p");
  //  checkIntPair(p, 3, 4);

  ctx.resume();
  SBValue pp = ctx.frame.FindVariable("pp");
  EXPECT_STREQ(pp.GetDisplayTypeName(), "MyPairPair");
  ASSERT_EQ((int)pp.GetNumChildren(), 2);
  SBValue ppFirst = pp.GetChildAtIndex(0);
  checkIntPair(ppFirst, 5, 6);
  SBValue ppSecond = pp.GetChildAtIndex(1);
  checkIntPair(ppSecond, 7, 8);
}

